// Runs the assembled app under real (Laragon) Apache in the foreground on 127.0.0.1:8081.
// Env overrides: HTTPD_BIN (httpd.exe path), PHP_DIR (PHP install dir).
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fwd = (p) => resolve(p).replaceAll('\\', '/');

const httpdBin = fwd(process.env.HTTPD_BIN
  ?? 'C:/laragon/bin/apache/httpd-2.4.68-260617-Win64-VS18/bin/httpd.exe');
const phpDir = fwd(process.env.PHP_DIR ?? 'C:/laragon/bin/php/php-8.5.11-Win32-vs17-x64');
const serverRoot = dirname(dirname(httpdBin));

const assemble = spawnSync(process.execPath, [join(root, 'scripts', 'assemble.mjs')], { stdio: 'inherit' });
if (assemble.status !== 0) process.exit(assemble.status ?? 1);

const apacheDir = join(root, 'dist', 'apache');
mkdirSync(apacheDir, { recursive: true });
const confPath = join(apacheDir, 'httpd.conf');

const loadFiles = ['libcrypto-3-x64.dll', 'libssl-3-x64.dll']
  .filter((f) => existsSync(join(phpDir, f)))
  .map((f) => `LoadFile "${phpDir}/${f}"`);

const conf = `# Generated by scripts/serve-apache.mjs - do not edit.
ServerRoot "${serverRoot}"
Listen 127.0.0.1:8081
ServerName 127.0.0.1
PidFile "${fwd(join(apacheDir, 'httpd.pid'))}"
ErrorLog "${fwd(join(apacheDir, 'error.log'))}"
LogLevel warn

LoadModule authz_core_module modules/mod_authz_core.so
LoadModule alias_module modules/mod_alias.so
LoadModule filter_module modules/mod_filter.so
LoadModule mime_module modules/mod_mime.so
LoadModule log_config_module modules/mod_log_config.so
LoadModule dir_module modules/mod_dir.so
LoadModule rewrite_module modules/mod_rewrite.so
LoadModule headers_module modules/mod_headers.so
LoadModule deflate_module modules/mod_deflate.so

${loadFiles.join('\n')}
LoadModule php_module "${phpDir}/php8apache2_4.dll"
PHPIniDir "${phpDir}"
AddHandler application/x-httpd-php .php

TypesConfig conf/mime.types
DocumentRoot "${fwd(join(root, 'dist', 'php', 'public'))}"

<Directory "${fwd(join(root, 'dist', 'php', 'public'))}">
    AllowOverride All
    Require all granted
</Directory>

# Local-only: mimic a typical host that gzips text responses (never put this in .htaccess).
AddOutputFilterByType DEFLATE text/plain text/html text/css application/javascript application/json
# Keep the app's ETag byte-identical (Apache would otherwise append "-gzip"; Spec allows that on real hosts,
# but the contract suite asserts the app's own strong ETag).
DeflateAlterETag NoChange
`;
writeFileSync(confPath, conf);

console.log(`Apache on http://127.0.0.1:8081 (conf: ${fwd(confPath)})`);
const child = spawn(httpdBin, ['-f', fwd(confPath)], { stdio: 'inherit' });
child.on('exit', (code) => process.exit(code ?? 0));
for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => child.kill());
